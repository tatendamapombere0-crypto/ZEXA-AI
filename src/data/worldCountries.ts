export const WORLD_COUNTRIES: CountryConfig[] = RAW_WORLD_COUNTRIES.map((c) => {
  const isLoaded = Boolean(c.hasCurriculumPack);
  const curriculum = c.curriculum || `${c.name} National Curriculum`;
  return {
    id: c.name,
    code: c.code,
    flag: c.flag,
    name: c.name,
    region: c.region,
    curriculum,
    curriculumLabel: curriculum,
    hasCurriculumPack: isLoaded,
    badge: isLoaded ? 'ZIMSEC · HBC' : c.region,
    description: isLoaded
      ? 'Full Zimbabwe national data, ZIMSEC Grade 7, O-Level & A-Level syllabi, ChiShona/IsiNdebele, and Heritage Studies.'
      : `${c.name} (${c.region})`
  };
});

export function findCountryConfig(countryName?: string): CountryConfig {
  const clean = (countryName || '').trim();
  const match = WORLD_COUNTRIES.find(
    (c) => c.name.toLowerCase() === clean.toLowerCase() || c.code.toLowerCase() === clean.toLowerCase()
  );
  if (match) return match;
  const fallbackName = clean || 'Selected Country';
  return {
    id: fallbackName,
    code: 'GLB',
    flag: '🌍',
    name: fallbackName,
    region: 'Global',
    curriculum: `${fallbackName} National Curriculum`,
    curriculumLabel: `${fallbackName} National Curriculum`,
    hasCurriculumPack: false,
    badge: 'Global',
    description: fallbackName
  };
}

export function hasCountryCurriculumPack(countryName?: string): boolean {
  return Boolean(findCountryConfig(countryName).hasCurriculumPack);
}
